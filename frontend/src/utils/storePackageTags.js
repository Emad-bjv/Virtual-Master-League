export function resolveItemTag(item) {
  if (!item) return null;
  // If custom tag text is present:
  if (item.custom_tag_text && String(item.custom_tag_text).trim()) {
    const palette = CUSTOM_TAG_PALETTES[item.custom_tag_color] || CUSTOM_TAG_PALETTES.ROSE_FIRE;
    return {
      isCustom: true,
      label: item.custom_tag_text.trim(),
      shortLabel: item.custom_tag_text.trim(),
      badgeClass: palette.badgeClass,
      border: palette.border,
      shadow: palette.shadow,
    };
  }
  // Otherwise if preset badge_tag is present:
  if (item.badge_tag && PACKAGE_TAGS[item.badge_tag]) {
    return {
      isCustom: false,
      ...PACKAGE_TAGS[item.badge_tag],
    };
  }
  return null;
}
